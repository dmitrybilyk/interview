package com.conduct.interview.coding.leetcode._1_arrays_and_hashing;

import java.util.Arrays;

// LC 238 — Product of Array Except Self
// Time O(n), Space O(1) (не рахуючи масиву result, який і так треба повернути)
//
// Задача: для кожного індексу i порахувати добуток УСІХ елементів масиву, КРІМ nums[i].
// Приклад: nums = [1, 2, 3, 4] -> результат = [24, 12, 8, 6]
//   result[0] = 2*3*4 = 24  (усе, крім nums[0]=1)
//   result[1] = 1*3*4 = 12  (усе, крім nums[1]=2)
//   result[2] = 1*2*4 = 8   (усе, крім nums[2]=3)
//   result[3] = 1*2*3 = 6   (усе, крім nums[3]=4)
//
// Найпростіше рішення: для кожного i перемножити все, крім nums[i] — це O(n²)
// (n елементів, для кожного окремий прохід довжини n).
// Або поділити добуток усіх елементів на nums[i] — O(n), але не можна, якщо в масиві є 0.
//
// ==================== ЯК ПРАЦЮЄ ЦЕ РІШЕННЯ (O(n), без ділення) ====================
// Ключова ідея: result[i] = (добуток усього ЗЛІВА від i) * (добуток усього СПРАВА від i).
// Рахуємо ці дві частини окремо, за два проходи масиву:
//
// ПРОХІД 1 (зліва направо) — кладемо в result[i] добуток усього, що ЗЛІВА від i:
//   nums:          [1,  2,  3,  4]
//   result після 1-го проходу:
//     result[0] = 1                     (зліва від індексу 0 нічого немає)
//     result[1] = result[0] * nums[0] = 1 * 1 = 1
//     result[2] = result[1] * nums[1] = 1 * 2 = 2
//     result[3] = result[2] * nums[2] = 2 * 3 = 6
//   result:        [1,  1,  2,  6]      <- це поки що ТІЛЬКИ "ліва" частина відповіді
//
// ПРОХІД 2 (справа наліво) — домножуємо кожен result[i] на добуток усього, що СПРАВА від i:
//   заводимо змінну suffix = 1 (накопичувач "правого" добутку, спочатку порожній)
//   i=3: result[3] = result[3](6) * suffix(1)  = 6   | потім suffix = suffix(1) * nums[3](4) = 4
//   i=2: result[2] = result[2](2) * suffix(4)  = 8   | потім suffix = suffix(4) * nums[2](3) = 12
//   i=1: result[1] = result[1](1) * suffix(12) = 12  | потім suffix = suffix(12) * nums[1](2) = 24
//   i=0: result[0] = result[0](1) * suffix(24) = 24  | потім suffix = suffix(24) * nums[0](1) = 24
//   result:        [24, 12, 8, 6]  <- готова відповідь, збігається з прикладом вище!
//
// Головне: suffix оновлюється ПІСЛЯ використання — на кожному кроці i він містить
// добуток елементів, що знаходяться ПРАВІШЕ за поточний i (сам nums[i] туди ще не входить).
public class ProductExceptSelf {

    public static int[] productExceptSelf(int[] nums) {
        int n = nums.length;
        int[] result = new int[n];
        result[0] = 1;
        // для першого елемента зліва нічого немає -> добуток зліва = 1

        for (int i = 1; i < n; i++) {
            result[i] = result[i - 1] * nums[i - 1]; // prefix
        }
        // ПРОХІД 1: result[i] = добуток усіх nums[0..i-1] (усе, що зліва від i)

        int suffix = 1;
        // ПРОХІД 2: suffix — добуток усіх елементів, що йдуть ПРАВІШЕ за поточний i.
        // Спочатку (для найправішого елемента) справа нічого немає, тому 1.

        for (int i = n - 1; i >= 0; i--) {
            result[i] *= suffix;
            // у result[i] вже лежить "лівий" добуток (з проходу 1) -> домножуємо на "правий" (suffix)
            // -> тепер result[i] = добуток УСІХ елементів, крім nums[i]. Саме це нам і треба.

            suffix *= nums[i]; // accumulate suffix on the fly
            // ТІЛЬКИ ТЕПЕР додаємо nums[i] у накопичувач — він знадобиться для СЛІДУЮЧОГО
            // (лівішого) i на наступній ітерації, де nums[i] вже буде "справа" від нього
        }
        return result;
    }

    public static void main(String[] args) {
        System.out.println(Arrays.toString(productExceptSelf(new int[]{1, 2, 3, 4}))); // [24,12,8,6]
    }
}
