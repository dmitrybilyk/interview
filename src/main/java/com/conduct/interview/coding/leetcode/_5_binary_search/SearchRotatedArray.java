package com.conduct.interview.coding.leetcode._5_binary_search;

// LC 33 — Search in Rotated Sorted Array
// Патерн: модифікований бінарний пошук — визначаємо, яка половина відсортована, і звужуємо межі
// Time O(log n), Space O(1)

// "Rotated" (обернений/зсунутий) масив — це відсортований масив, який розрізали в якійсь точці
// та переставили частини місцями: [0,1,2,4,5,6,7] -> [4,5,6,7,0,1,2].
// Кожна з двох частин сама по собі відсортована, але весь масив разом — вже ні (є "розрив": 7 > 0).
public class SearchRotatedArray {

    public static int search(int[] nums, int target) {
        int lo = 0, hi = nums.length - 1;
        // lo — лівий край поточного вікна пошуку, hi — правий край

        while (lo <= hi) {
            // поки вікно пошуку не порожнє (lo не перескочив hi)

            int mid = lo + (hi - lo) / 2;
            // середина вікна; формула (а не (lo+hi)/2) захищає від переповнення int

            if (nums[mid] == target) {
                return mid;
                // знайшли елемент точно в середині — повертаємо індекс
            }

            if (nums[lo] <= nums[mid]) { // ліва половина (nums[lo..mid]) відсортована
                // це означає, що "розрив" (точка обертання) НЕ потрапляє в [lo..mid],
                // тобто ці елементи йдуть строго за зростанням

                if (nums[lo] <= target && target < nums[mid]) {
                    hi = mid - 1;
                    // target лежить у межах відсортованої лівої половини — звужуємо вікно вліво
                } else {
                    lo = mid + 1;
                    // інакше target може бути тільки в правій половині (де є розрив) — звужуємо вправо
                }

            } else {                     // права половина (nums[mid..hi]) відсортована
                // якщо ліва половина НЕ відсортована — значить розрив саме в ній,
                // а отже права половина точно без розриву й відсортована за зростанням

                if (nums[mid] < target && target <= nums[hi]) {
                    lo = mid + 1;
                    // target лежить у межах відсортованої правої половини — звужуємо вікно вправо
                } else {
                    hi = mid - 1;
                    // інакше target може бути тільки в лівій половині (де є розрив) — звужуємо вліво
                }
            }
        }
        return -1;
        // вікно пошуку спорожніло, а елемент так і не знайшли — його немає в масиві
    }

    public static void main(String[] args) {
        System.out.println(search(new int[]{4,5,6,7,0,1,2}, 0)); // 4
        System.out.println(search(new int[]{4,5,6,7,0,1,2}, 3)); // -1
    }
}
