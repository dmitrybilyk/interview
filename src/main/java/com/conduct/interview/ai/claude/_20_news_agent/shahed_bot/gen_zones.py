"""
Генерує zones.py на основі даних OpenStreetMap (Overpass API).
Запуск: python gen_zones.py
"""

import json
import time
import requests

OVERPASS = "https://overpass-api.de/api/interpreter"

# Центри зон (lat, lon)
# Центр міста — географічний центр Львова
# Зони — зміщені на ~7км від центру, щоб 20км радіус охопив передмістя
ZONE_CENTERS = {
    "all":    (49.8397, 24.0297, 20_000),  # весь Львів — центр міста, 20км
    "center": (49.8397, 24.0297, 7_000),   # центр міста, 7км
    "north":  (49.900,  24.020,  15_000),  # Брюховичі / Рясне напрямок
    "east":   (49.845,  24.130,  15_000),  # Грибовичі напрямок
    "west":   (49.840,  23.940,  15_000),  # Страдч / Зимна Вода захід
    "south":  (49.770,  24.030,  15_000),  # Зимна Вода / Суховоля напрямок
}

ZONE_NAMES = {
    "all":    "🌍 Весь Львів (20 км)",
    "center": "🏙 Центр",
    "north":  "⬆️ Північ",
    "east":   "➡️ Схід",
    "west":   "⬅️ Захід",
    "south":  "⬇️ Південь",
}


def fetch_places(lat: float, lon: float, radius: int) -> list[str]:
    query = f"""
[out:json][timeout:30];
(
  node["place"~"^(city|town|village|suburb|neighbourhood|hamlet)$"]
      (around:{radius},{lat},{lon});
  way["place"~"^(city|town|village|suburb|neighbourhood|hamlet)$"]
     (around:{radius},{lat},{lon});
);
out tags;
"""
    r = requests.post(OVERPASS,
                      data=f"data={requests.utils.quote(query)}",
                      headers={"Content-Type": "application/x-www-form-urlencoded"},
                      timeout=40)
    r.raise_for_status()
    data = r.json()

    names = set()
    for el in data.get("elements", []):
        tags = el.get("tags", {})
        for key in ("name:uk", "name"):
            name = tags.get(key, "").strip()
            if name:
                names.add(name)
                break

    return sorted(names)


def to_stem(name: str) -> str:
    """Бере перші 5+ символів як стем для покриття відмінків."""
    name = name.lower()
    # Для коротких назв (до 6 символів) беремо повністю
    if len(name) <= 6:
        return name
    # Для довших — відкидаємо останні 2 символи (типове закінчення)
    return name[:-2]


def main():
    zones_data = {}

    for zone_key, (lat, lon, radius) in ZONE_CENTERS.items():
        print(f"Запит {zone_key} ({lat}, {lon}, r={radius}m)...")
        places = fetch_places(lat, lon, radius)
        print(f"  Знайдено {len(places)} населених пунктів")
        for p in places:
            print(f"    {p}")

        stems = sorted({to_stem(p) for p in places if p})
        zones_data[zone_key] = {
            "name":  ZONE_NAMES[zone_key],
            "stems": stems,
            "places": places,  # для довідки
        }
        time.sleep(2)  # пауза між запитами до Overpass

    # Зберігаємо сирі дані
    with open("zones_raw.json", "w", encoding="utf-8") as f:
        json.dump(zones_data, f, ensure_ascii=False, indent=2)
    print("\nСирі дані збережено в zones_raw.json")

    # Генеруємо zones.py
    lines = ['"""Auto-generated by gen_zones.py — не редагуй вручну."""\n\nZONES = {\n']
    for zone_key, data in zones_data.items():
        lines.append(f'    "{zone_key}": {{\n')
        lines.append(f'        "name": "{data["name"]}",\n')
        lines.append(f'        "stems": [\n')
        for stem in data["stems"]:
            lines.append(f'            "{stem}",\n')
        lines.append(f'        ],\n')
        lines.append(f'    }},\n')
    lines.append("}\n")

    with open("zones.py", "w", encoding="utf-8") as f:
        f.writelines(lines)
    print("zones.py оновлено!")


if __name__ == "__main__":
    main()
